#!/usr/bin/env python3
"""
Script to clean up posts that were deleted from e621 for AI-generated content.

This script:
1. Finds deleted posts with AI-related deletion reasons
2. Unfavorites posts from e621 via API
3. Optionally deletes the local files
4. Removes posts from database
5. Archives post information before deletion

Usage:
    python scripts/database/cleanup_ai_generated_posts.py                # Dry-run mode
    python scripts/database/cleanup_ai_generated_posts.py --execute      # Execute cleanup
    python scripts/database/cleanup_ai_generated_posts.py --delete-files # Also delete local files
"""

import sys
import os
import logging
import argparse
import json
import time
from datetime import datetime
from pathlib import Path

from fff.archive import paths as archive_paths

from fff.archive.config import load_config
from fff.archive.db import connect_to_mysql, create_tables_if_not_exists
from send2trash import send2trash
import requests

def setup_logging():
    """Setup logging."""
    log_dir = str(archive_paths.LOG_DIR)
    os.makedirs(log_dir, exist_ok=True)

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    log_file = f"{log_dir}/{timestamp}_cleanup_ai_posts.log"

    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(levelname)s - %(message)s',
        handlers=[
            logging.FileHandler(log_file),
            logging.StreamHandler()
        ]
    )

    return log_file

def get_ai_generated_posts(conn):
    """Get deleted posts with AI-related deletion reasons.

    Returns:
        List of dicts with post information (id, file_path, file_name, deletion_reason, etc.)
    """
    cursor = conn.cursor(dictionary=True)
    try:
        # Search for common AI-related terms in deletion reasons
        query = """
            SELECT
                id,
                MIN(a.artist_id) AS artist_id,
                file_path,
                file_name,
                rating,
                deletion_reason,
                deleted_at,
                ingested_at,
                updated_at
            FROM posts
            LEFT JOIN posts_artists pa ON pa.post_id = posts.id
            LEFT JOIN artists a ON a.artist_id = pa.artist_id
            WHERE deleted = 1
            AND deletion_reason IS NOT NULL
            AND (
                deletion_reason LIKE '%AI generated%'
                or deletion_reason LIKE '%AI assisted%'
                OR deletion_reason LIKE '%AI-generated%'
                OR deletion_reason LIKE '%ai_generated%'
                OR deletion_reason LIKE '%artificial intelligence%'
                OR deletion_reason LIKE '%machine learning%'
                OR deletion_reason LIKE '%generated by AI%'
                OR deletion_reason LIKE '%created by AI%'
                OR deletion_reason LIKE '%AI content%'
                OR deletion_reason LIKE '%AI image%'
                OR deletion_reason LIKE '%AI art%'
            )
            GROUP BY id, file_path, file_name, rating, deletion_reason,
                     deleted_at, ingested_at, updated_at
            ORDER BY deleted_at DESC
        """

        cursor.execute(query)
        results = cursor.fetchall()

        # Add file existence flag
        for post in results:
            file_path = post.get('file_path')
            post['file_exists'] = bool(file_path and os.path.exists(file_path))
            post['snapshot_json'] = json.dumps(
                build_post_snapshot(conn, post['id']),
                default=str,
                ensure_ascii=False,
            )

        return results
    finally:
        cursor.close()


def build_post_snapshot(conn, post_id):
    """Capture the post and all archive-relevant related rows before deletion."""
    snapshot = {"post_id": post_id, "captured_at": datetime.now().isoformat()}

    def rows(query, params=(post_id,)):
        cursor = conn.cursor(dictionary=True)
        try:
            cursor.execute(query, params)
            return cursor.fetchall()
        finally:
            cursor.close()

    snapshot["post"] = rows("SELECT * FROM posts WHERE id = %s")
    snapshot["artist_links"] = rows("SELECT * FROM posts_artists WHERE post_id = %s")
    snapshot["artists"] = rows(
        """
        SELECT a.*
        FROM artists a
        JOIN posts_artists pa ON pa.artist_id = a.artist_id
        WHERE pa.post_id = %s
        ORDER BY a.artist_id
        """
    )
    snapshot["tag_links"] = rows("SELECT * FROM posts_tags WHERE post_id = %s")
    snapshot["tags"] = rows(
        """
        SELECT t.*
        FROM tags t
        JOIN posts_tags pt ON pt.tag_id = t.tag_id
        WHERE pt.post_id = %s
        ORDER BY t.tag_id
        """
    )
    snapshot["source_links"] = rows("SELECT * FROM source_links WHERE post_id = %s")
    snapshot["pool_links"] = rows("SELECT * FROM posts_pools WHERE post_id = %s")
    snapshot["perceptual_hashes"] = rows(
        "SELECT * FROM e621_perceptual_hashes WHERE post_id = %s"
    )
    snapshot["artist_file_renames"] = rows(
        "SELECT * FROM artist_file_renames WHERE post_id = %s"
    )
    snapshot["relationships"] = rows(
        "SELECT * FROM post_relationships WHERE post_id = %s"
    )
    snapshot["takedown_links"] = rows(
        "SELECT * FROM post_takedowns WHERE post_id = %s"
    )

    takedown_ids = [row["takedown_id"] for row in snapshot["takedown_links"]]
    snapshot["takedowns"] = []
    if takedown_ids:
        placeholders = ",".join(["%s"] * len(takedown_ids))
        snapshot["takedowns"] = rows(
            f"SELECT * FROM takedowns WHERE takedown_id IN ({placeholders})",
            tuple(takedown_ids),
        )

    pool_ids = [row["pool_id"] for row in snapshot["pool_links"]]
    snapshot["pools"] = []
    if pool_ids:
        placeholders = ",".join(["%s"] * len(pool_ids))
        snapshot["pools"] = rows(
            f"SELECT * FROM pools WHERE pool_id IN ({placeholders})",
            tuple(pool_ids),
        )

    return snapshot

def archive_ai_posts_info(conn, posts):
    """Archive AI-generated posts in the database before deletion."""
    try:
        query = """
            INSERT INTO ai_generated_posts_archive
                (post_id, artist_id, file_name, file_path, rating, deletion_reason,
                  deleted_at, ingested_at, updated_at, file_exists, snapshot_json)
              VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
            ON DUPLICATE KEY UPDATE
                artist_id = VALUES(artist_id),
                file_name = VALUES(file_name),
                file_path = VALUES(file_path),
                rating = VALUES(rating),
                deletion_reason = VALUES(deletion_reason),
                deleted_at = VALUES(deleted_at),
                ingested_at = VALUES(ingested_at),
                updated_at = VALUES(updated_at),
                file_exists = VALUES(file_exists),
                snapshot_json = VALUES(snapshot_json)
        """
        values = [
            (post['id'], post.get('artist_id'), post.get('file_name'), post.get('file_path'), post.get('rating'),
             post.get('deletion_reason'), post.get('deleted_at'), post.get('ingested_at'),
             post.get('updated_at'), bool(post.get('file_exists')), post.get('snapshot_json'))
            for post in posts
        ]
        cursor = conn.cursor()
        cursor.executemany(query, values)
        conn.commit()
        cursor.close()
        logging.info("Archived %d AI-generated post records to ai_generated_posts_archive", len(posts))
        return True
    except Exception as e:
        conn.rollback()
        logging.error(f"Failed to archive posts: {e}")
        return False

def unfavorite_on_e621(post_id, e621_config):
    """Remove a post from e621 favorites via API.

    Args:
        post_id: The e621 post ID to unfavorite
        e621_config: Configuration dict with login, api_key, and user_agent

    Returns:
        True if successful or already unfavorited, False on error
    """
    url = f"https://e621.net/favorites/{post_id}.json"
    auth = (e621_config.get("login"), e621_config.get("api_key"))
    user_agent = e621_config.get("user_agent", "e621 archive/1.0")

    try:
        response = requests.delete(url, auth=auth, headers={"User-Agent": user_agent})

        # Accept both 200 (OK) and 204 (No Content) as success
        if response.status_code in [200, 204]:
            logging.debug(f"Successfully unfavorited post {post_id} on e621")
            return True
        # 404 or 422 means post was already unfavorited or doesn't exist - that's OK
        elif response.status_code in [404, 422]:
            logging.debug(f"Post {post_id} was already unfavorited or doesn't exist on e621")
            return True
        else:
            logging.warning(f"Failed to unfavorite post {post_id}: HTTP {response.status_code}")
            return False
    except Exception as e:
        logging.error(f"Error unfavoriting post {post_id}: {e}")
        return False

def unfavorite_posts_batch(post_ids, e621_config):
    """Unfavorite multiple posts from e621 with rate limiting.

    Args:
        post_ids: List of post IDs to unfavorite
        e621_config: Configuration dict with API credentials

    Returns:
        Dict with statistics: {'success': count, 'failed': count}
    """
    stats = {'success': 0, 'failed': 0}

    logging.info(f"Unfavoriting {len(post_ids)} posts from e621...")

    for i, post_id in enumerate(post_ids, 1):
        if unfavorite_on_e621(post_id, e621_config):
            stats['success'] += 1
        else:
            stats['failed'] += 1

        # Rate limiting: 1 request per second (e621 API limit is 2/sec, but be conservative)
        if i < len(post_ids):  # Don't sleep after the last one
            time.sleep(1)

        # Progress logging every 10 posts
        if i % 10 == 0:
            logging.info(f"  Unfavorited {i}/{len(post_ids)} posts...")

    logging.info(f"Unfavorite complete: {stats['success']} successful, {stats['failed']} failed")
    return stats

def delete_posts_from_db(conn, post_ids):
    """Delete posts from database by IDs and ALL related records.

    This uses CASCADE DELETE to automatically remove all traces of posts from:
    - posts_tags (tag associations)
    - posts_artists (artist associations)
    - source_links (source URLs)
    - posts_pools (pool memberships)
    - post_relationships (parent/child relationships)
    - post_takedowns (takedown notice links)
    - e621_perceptual_hashes (cached hashes)
    - artist_file_renames (rename history)

    The CASCADE is handled automatically by foreign key constraints in the database schema.
    """
    if not post_ids:
        return

    cursor = conn.cursor()
    try:
        placeholders = ','.join(['%s'] * len(post_ids))

        # Count related records before deletion for reporting
        related_counts = {}
        tables_to_check = [
            'posts_tags',
            'posts_artists',
            'source_links',
            'posts_pools',
            'post_relationships',
            'post_takedowns',
            'e621_perceptual_hashes',
            'artist_file_renames'
        ]

        logging.info(f"Checking related records for {len(post_ids)} posts...")
        for table in tables_to_check:
            try:
                count_query = f"SELECT COUNT(*) FROM {table} WHERE post_id IN ({placeholders})"
                cursor.execute(count_query, post_ids)
                count = cursor.fetchone()[0]
                if count > 0:
                    related_counts[table] = count
                    logging.info(f"  - {table}: {count} records")
            except Exception as e:
                logging.debug(f"Could not check {table}: {e}")

        # Delete from posts table - CASCADE will handle all related tables
        query = f"DELETE FROM posts WHERE id IN ({placeholders})"
        cursor.execute(query, post_ids)
        deleted_count = cursor.rowcount
        conn.commit()

        logging.info(f"[OK] Deleted {deleted_count} posts from database")
        if related_counts:
            total_related = sum(related_counts.values())
            logging.info(f"[OK] Cascade deleted {total_related} related records across {len(related_counts)} tables")
        else:
            logging.info(f"[OK] No related records found (posts were isolated)")

    except Exception as e:
        logging.error(f"Failed to delete posts from database: {e}")
        conn.rollback()
        raise
    finally:
        cursor.close()

def cleanup_ai_generated_posts(conn, e621_config, delete_files=False, dry_run=True):
    """
    Clean up AI-generated posts.

    Args:
        conn: Database connection
        e621_config: Configuration dict with API credentials for unfavoriting
        delete_files: If True, delete local files using send2trash
        dry_run: If True, only report what would be done without executing

    Returns:
        Dict with statistics about the cleanup operation
    """
    stats = {
        'total_found': 0,
        'files_exist': 0,
        'unfavorited': 0,
        'unfavorite_failed': 0,
        'files_deleted': 0,
        'files_failed': 0,
        'posts_deleted': 0,
        'dry_run': dry_run
    }

    # Find AI-generated posts
    logging.info("Searching for AI-generated deleted posts...")
    ai_posts = get_ai_generated_posts(conn)
    stats['total_found'] = len(ai_posts)

    if not ai_posts:
        logging.info("No AI-generated posts found.")
        return stats

    logging.info(f"Found {len(ai_posts)} AI-generated deleted posts")

    # Count how many have existing files
    stats['files_exist'] = sum(1 for p in ai_posts if p['file_exists'])
    logging.info(f"  - {stats['files_exist']} have existing local files")
    logging.info(f"  - {len(ai_posts) - stats['files_exist']} files already deleted/missing")

    # Show sample of deletion reasons
    logging.info("\nSample deletion reasons:")
    for i, post in enumerate(ai_posts[:5], 1):
        reason = post['deletion_reason'][:100] + '...' if len(post['deletion_reason']) > 100 else post['deletion_reason']
        logging.info(f"  {i}. Post {post['id']}: {reason}")
    if len(ai_posts) > 5:
        logging.info(f"  ... and {len(ai_posts) - 5} more")

    if dry_run:
        logging.info("\n" + "="*80)
        logging.info("DRY RUN MODE - No changes will be made")
        logging.info("="*80)
        logging.info(f"\nWould unfavorite {len(ai_posts)} posts from e621")
        logging.info(f"Would delete {len(ai_posts)} posts from database")
        if delete_files:
            logging.info(f"Would delete {stats['files_exist']} local files")
        else:
            logging.info("File deletion disabled (use --delete-files to enable)")
        logging.info("\nRun with --execute to perform cleanup")
        return stats

    # Archive before deletion
    logging.info("\nArchiving post information...")
    if not archive_ai_posts_info(conn, ai_posts):
        logging.error("Failed to archive post information - ABORTING for safety")
        return stats

    # Unfavorite posts from e621 first
    logging.info("\nUnfavoriting posts from e621...")
    post_ids = [p['id'] for p in ai_posts]
    unfavorite_stats = unfavorite_posts_batch(post_ids, e621_config)
    stats['unfavorited'] = unfavorite_stats['success']
    stats['unfavorite_failed'] = unfavorite_stats['failed']

    if stats['unfavorite_failed'] > 0:
        logging.warning(f"Failed to unfavorite {stats['unfavorite_failed']} posts - continuing with cleanup")

    # Delete files if requested
    if delete_files and stats['files_exist'] > 0:
        logging.info(f"\nDeleting {stats['files_exist']} local files...")
        for post in ai_posts:
            if post['file_exists']:
                file_path = post['file_path']
                try:
                    send2trash(file_path)
                    stats['files_deleted'] += 1
                    logging.info(f"  Deleted file: {file_path}")
                except Exception as e:
                    stats['files_failed'] += 1
                    logging.error(f"  Failed to delete {file_path}: {e}")

        logging.info(f"File deletion complete: {stats['files_deleted']} deleted, {stats['files_failed']} failed")
    elif stats['files_exist'] > 0:
        logging.info(f"\nSkipping file deletion for {stats['files_exist']} files (--delete-files not specified)")

    # Delete posts from database
    logging.info("\nDeleting posts from database...")
    try:
        delete_posts_from_db(conn, post_ids)
        stats['posts_deleted'] = len(post_ids)
        logging.info(f"Database cleanup complete: {stats['posts_deleted']} posts deleted")
    except Exception as e:
        logging.error(f"Database deletion failed: {e}")
        return stats

    return stats

def main(argv=None):
    """Main entry point."""
    parser = argparse.ArgumentParser(
        description="Clean up AI-generated posts that were deleted from e621",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Preview what would be deleted (dry-run)
  python scripts/database/cleanup_ai_generated_posts.py

  # Execute cleanup (keep files on disk)
  python scripts/database/cleanup_ai_generated_posts.py --execute

  # Execute cleanup and delete local files
  python scripts/database/cleanup_ai_generated_posts.py --execute --delete-files
        """
    )

    parser.add_argument(
        '--execute',
        action='store_true',
        help='Execute the cleanup (default is dry-run mode)'
    )

    parser.add_argument(
        '--delete-files',
        action='store_true',
        help='Also delete local files (moves to trash/recycle bin)'
    )

    args = parser.parse_args(argv)

    # Setup logging
    log_file = setup_logging()
    logging.info(f"Logging to: {log_file}")

    # Load config
    try:
        config = load_config()
    except Exception as e:
        logging.error(f"Failed to load config: {e}")
        return 1

    # Connect to database
    try:
        conn = connect_to_mysql(config["mysql"])
        create_tables_if_not_exists(conn)
    except Exception as e:
        logging.error(f"Failed to connect to database: {e}")
        return 1

    try:
        # Run cleanup
        stats = cleanup_ai_generated_posts(
            conn,
            e621_config=config["e621"],
            delete_files=args.delete_files,
            dry_run=not args.execute
        )

        # Print summary
        logging.info("\n" + "="*80)
        logging.info("CLEANUP SUMMARY")
        logging.info("="*80)
        logging.info(f"Mode: {'DRY RUN' if stats['dry_run'] else 'EXECUTED'}")
        logging.info(f"AI-generated posts found: {stats['total_found']}")
        logging.info(f"Posts with existing files: {stats['files_exist']}")

        if not stats['dry_run']:
            logging.info(f"Posts unfavorited from e621: {stats['unfavorited']}")
            if stats['unfavorite_failed'] > 0:
                logging.info(f"Unfavorite failed: {stats['unfavorite_failed']}")
            logging.info(f"Files deleted: {stats['files_deleted']}")
            if stats['files_failed'] > 0:
                logging.info(f"Files failed: {stats['files_failed']}")
            logging.info(f"Posts removed from database: {stats['posts_deleted']}")

        logging.info("="*80)

        if stats['dry_run'] and stats['total_found'] > 0:
            logging.info("\nRun with --execute to perform the cleanup")

        return 0

    except Exception as e:
        logging.error(f"Cleanup failed: {e}", exc_info=True)
        return 1
    finally:
        conn.close()

if __name__ == "__main__":
    sys.exit(main())
